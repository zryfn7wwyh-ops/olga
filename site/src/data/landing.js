/*
 * Конфигурация лендинга. Блоки идут на странице в порядке массива.
 * id — постоянный якорь (#program, #education, …), nav — подпись в меню, title — заголовок блока.
 *
 * Содержимое блока — массив parts, каждая часть одного из типов:
 *   { type: 'text', text }              — абзац
 *   { type: 'subhead', text }           — подзаголовок внутри блока
 *   { type: 'list', items }             — маркированный список
 *   { type: 'fields', rows: [{ label, value }] } — таблица «поле — значение»
 *   { type: 'table', columns, rows }    — таблица с колонками
 *   { type: 'docs', items, status }     — документы (см. ниже)
 *   { type: 'notice', text }            — официальное уведомление
 *   { type: 'teachers', items }         — карточки преподавателей
 *   { type: 'groups', items: [{ title, parts }] } — две колонки с подблоками
 *
 * Документ: { title, file, format, size, date }
 *   file: 'docs/x.pdf'  → ссылка «Скачать». Файлы кладутся в public/docs/; fileName — имя файла при сохранении;
 *   file: null          → нейтральная пометка из status (например, «Документ будет добавлен»);
 *   note — подпись под названием (например, реквизиты приказа), иначе выводится date.
 *
 * Поля без подтверждённых данных на сайт не выводятся — их просто нет в конфигурации.
 */

